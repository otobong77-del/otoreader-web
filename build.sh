#!/bin/bash
# Bundles the phone app's pagination script so the web page can inject it into each chapter.
cd "$(dirname "$0")"
node -e 'const fs=require("fs");fs.writeFileSync("reader.bundle.js","/* generated by build.sh from android-app/app/src/main/assets/reader.js */\nwindow.READER_JS="+JSON.stringify(fs.readFileSync((process.argv[2] || "../omnibus-tools/android-app/app/src/main/assets/reader.js"),"utf8"))+";\n")'
echo "reader.bundle.js written"
